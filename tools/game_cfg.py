    pages: int
    cockpit_pages: int
    chip_names: int          # 콕핏 폰트로 그려지는 칩 이름 아카이브(롬 주소)
    cht_symbols: list
    text_fixes: dict = field(default_factory=dict)
    simple_db: tuple = ()    # 짧은 문자열 아카이브용 DB(E9 = printBuffer 3바이트). 아카이브별로 컬렉션 일본어판에 맞춰 고른다
    # 한글 롬이 번역하지 않은 아카이브: 글자 구간(줄바꿈 포함) 통째 치환. 번역 메모리 + 직접 번역
    run_archives: tuple = ()
    run_fixes: dict = field(default_factory=dict)
    tm_file: str = ''
    run_subs: tuple = ()     # run_archives 에서 통째 치환이 안 된 구간에 적용하는 부분 치환
    run_regex: tuple = ()    # 그다음 적용하는 정규식 치환 (패턴, 바꿀 말)
    # 폰트 형식: 'single' = 1024x1024 한 벌(EXE1·2), 'dual' = 2048x1024 왼쪽 그림자 판 + 오른쪽 맨 글자 판(EXE3)
    font_style: str = 'single'
    menu_prefix: str = 'cockpit_font_cht'   # 메뉴(콕핏) 폰트 파일 접두사
    menu_style: str = 'cockpit'             # 'cockpit' = 하늘색+외곽선, 'shadow' = 흰 글자+갈색 그림자
    font_owner: str = ''                    # 폰트를 다른 게임 폴더와 공유하면 그 폴더(EXE3 블랙 -> exe3)
    k_tables: tuple = ()                    # hangul_mode 'exe3': (encoding.json, low_inventory.json)
    # 번체판이 고정 칸(아이콘)으로 그리는 기호: 한글 롬 글자 -> 번체 코드. 그 칸은 그리지도 비우지도 않는다.
    # 제니 기호는 아이콘 목록(fixed_color_cht.txt)에 없어서, 빼먹으면 "안 쓰는 칸"으로 지워진다.
    char_codes: dict = field(default_factory=dict)
    char_alias: dict = field(default_factory=dict)   # 같은 뜻의 한글 롬 글자 -> 대표 글자(EXE3 「;」= 제니)
    # 게임 공통 부분 치환: (옛 글자열, 새 글자 목록). 다글자 기호([SwitchB] 등)는 목록 원소 하나로
    line_subs: tuple = ()

    @property
    def game_dir(self):
        return ROOT / '_work' / 'romfs' / self.key

    @property
    def out_dir(self):
        return ROOT / 'build' / 'romfs' / self.key / 'data'

    def icons(self):
        txt = (self.game_dir / 'data' / 'msg' / 'fixed_color_cht.txt').read_text(encoding='utf-8')
        return {int(x) for x in txt.split()}


