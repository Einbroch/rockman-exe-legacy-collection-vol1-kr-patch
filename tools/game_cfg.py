# 번체 0페이지 배치가 기호·한자가 섞여 있다 → 공백·숫자(0~10)만 원래 칸 유지
def _cht_symbols_exe3():
    """번체 EXE3 폰트 0페이지(원본 그림으로 확인): 0 공백, 1~10 숫자, 92~117 A~Z, 118 z, 119~128 기호,
    129~134 Σ Ω V2~V5, 160~184 a~y, 185 가운뎃점. 사이사이(11~91, 135~159)는 한자 -> None(한글에 쓰지 않음).
    칩 코드 글자 등은 게임이 이 칸 번호로 직접 찍는다(덮으면 칩 폴더 코드가 한글로 나옴)."""
    s = [None] * 186
    s[0] = ' '
    for i, ch in enumerate('0123456789'):
        s[1 + i] = ch
    for i in range(26):
        s[92 + i] = chr(ord('A') + i)
    for i, ch in enumerate(['z', 'ー', ':', '?', '+', '!', '、', '。', '/', '&', '*', 'Σ', 'Ω',
                            '[V2]', '[V3]', '[V4]', '[V5]']):
        s[118 + i] = ch
    for i in range(25):
        s[160 + i] = chr(ord('a') + i)
    s[185] = '·'
    return s


